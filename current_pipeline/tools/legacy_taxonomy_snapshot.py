"""Materialize the taxonomy overlay snapshot locked by legacy finalized v1."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def materialize_locked_overlays(
    *,
    repo_root: Path,
    output_root: Path,
    contract: dict[str, Any],
) -> tuple[Path, ...]:
    """Create the frozen reviewed overlay without modifying current taxonomy.

    The reviewed taxonomy file can legitimately gain profiles after a frozen
    release.  Legacy v1 must not silently consume them.  The contract records
    which post-freeze profiles are removed, and the generated byte stream must
    still match the original locked SHA-256 before it is used.
    """

    locked = contract["locked_sha256"]
    gap = repo_root / "rules/organism_taxonomy_gap_resolution_v1.json"
    auto = repo_root / "rules/organism_taxonomy_auto_v1.json"
    reviewed_current = repo_root / "rules/organism_taxonomy_reviewed_v1.json"
    for path, expected, label in (
        (gap, locked["taxonomy_gap_resolution_overlay"], "gap overlay"),
        (auto, locked["taxonomy_auto_overlay"], "auto overlay"),
    ):
        actual = _sha256(path)
        if actual != expected:
            raise ValueError(
                f"Locked taxonomy {label} changed: {actual} != {expected}"
            )

    payload = json.loads(reviewed_current.read_text(encoding="utf-8-sig"))
    exact_profiles = payload.get("exact_profiles")
    if not isinstance(exact_profiles, dict):
        raise ValueError("Reviewed taxonomy overlay has no exact_profiles object")
    removed: list[str] = []
    for key in contract.get("taxonomy_reviewed_postfreeze_profiles") or []:
        if key not in exact_profiles:
            raise ValueError(f"Expected post-freeze taxonomy profile missing: {key}")
        exact_profiles.pop(key)
        removed.append(key)

    resolved_output_root = (
        output_root if output_root.is_absolute() else repo_root / output_root
    )
    snapshot_root = resolved_output_root / "00_locked_release_snapshot"
    snapshot_root.mkdir(parents=True, exist_ok=True)
    reviewed_snapshot = snapshot_root / "organism_taxonomy_reviewed_v1.json"
    # The locked Windows snapshot used CRLF; preserve its exact byte form so
    # the historical hash remains meaningful.
    serialized = (json.dumps(payload, ensure_ascii=False, indent=2) + "\n").replace(
        "\n", "\r\n"
    )
    reviewed_snapshot.write_bytes(serialized.encode("utf-8"))
    actual_reviewed = _sha256(reviewed_snapshot)
    expected_reviewed = locked["taxonomy_reviewed_overlay"]
    if actual_reviewed != expected_reviewed:
        raise ValueError(
            "Cannot reconstruct locked reviewed taxonomy overlay: "
            f"{actual_reviewed} != {expected_reviewed}"
        )
    manifest = {
        "schema_version": "legacy_taxonomy_snapshot.v1",
        "source_current_reviewed_overlay": str(reviewed_current.resolve()),
        "postfreeze_profiles_removed": removed,
        "reviewed_snapshot": str(reviewed_snapshot.resolve()),
        "reviewed_snapshot_sha256": actual_reviewed,
        "gap_overlay_sha256": _sha256(gap),
        "auto_overlay_sha256": _sha256(auto),
    }
    (snapshot_root / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return (gap.resolve(), auto.resolve(), reviewed_snapshot.resolve())
